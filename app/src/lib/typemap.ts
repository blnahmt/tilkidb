// Column types moved between engines, and the CREATE TABLE for a table copied to another connection.
import type { Engine, Table } from "./api.ts";
import { literal, qualified, quoteIdent } from "./sqlgen.ts";

/** The closest type on `to` for a `from` column type. Same engine: unchanged. */
export function portType(type: string, from: Engine, to: Engine, isKey = false): string {
  if (from === to) return type;
  const t = type.toLowerCase().trim();
  const size = /\(([^)]*)\)/.exec(t)?.[1];
  const arr = t.endsWith("[]");
  const is = (re: RegExp) => re.test(t);
  if (to === "sqlite") {
    if (is(/^bool|^bit\(1\)|^tinyint\(1\)/) || is(/int|serial/)) return "INTEGER";
    if (is(/numeric|decimal|money/)) return "NUMERIC";
    if (is(/float|double|real/)) return "REAL";
    if (is(/blob|bytea|binary/)) return "BLOB";
    return "TEXT";
  }
  if (to === "postgres") {
    if (is(/^tinyint\(1\)|^bit\(1\)|^bool/)) return "boolean";
    if (is(/unsigned/) && is(/int/)) return is(/bigint/) ? "numeric(20)" : "bigint";
    if (is(/^(tiny|small)int/)) return "smallint";
    if (is(/^(medium)?int(eger)?\b|^int\(/)) return from === "sqlite" ? "bigint" : "integer";
    if (is(/^bigint/)) return "bigint";
    if (is(/^(decimal|numeric)/)) return size ? `numeric(${size})` : "numeric";
    if (is(/^double|^real/) && from === "sqlite") return "double precision";
    if (is(/^double/)) return "double precision";
    if (is(/^float|^real/)) return "real";
    if (is(/^datetime|^timestamp/)) return "timestamp";
    if (is(/^date$|^time$|^time\(/)) return t;
    if (is(/^year/)) return "integer";
    if (is(/^(var)?char/)) return t.startsWith("var") ? `varchar(${size ?? 255})` : `char(${size ?? 1})`;
    if (is(/blob|binary/)) return "bytea";
    if (is(/^json/)) return "jsonb";
    return "text"; // text variants, enum(...), set(...), anything unknown
  }
  // MySQL / MariaDB
  if (arr) return "json";
  if (is(/^bool/)) return "tinyint(1)";
  if (is(/^smallint|^int2/)) return "smallint";
  if (is(/^(integer|int4|int|serial)$/)) return from === "sqlite" ? "bigint" : "int";
  if (is(/^(bigint|int8|bigserial)/)) return "bigint";
  if (is(/^(numeric|decimal)/)) return size ? `decimal(${size})` : "decimal(30,10)";
  if (is(/^real|^float4/)) return from === "sqlite" ? "double" : "float";
  if (is(/^double|^float/)) return "double";
  if (is(/^timestamp|^datetime/)) return "datetime(6)";
  if (is(/^date$|^time/)) return t.replace(/ with(out)? time zone/, "");
  if (is(/^uuid/)) return "char(36)";
  if (is(/^json/)) return "json";
  if (is(/bytea|blob/)) return "longblob";
  if (is(/^(character varying|varchar)/)) return `varchar(${size ?? 255})`;
  if (is(/^(character|char)\b/)) return `char(${size ?? 1})`;
  return isKey ? "varchar(255)" : "longtext"; // MySQL can't key a TEXT column
}

/**
 * CREATE TABLE on `to` for a copy of `t` from `from`: columns, NOT NULL and the primary key.
 * A single integer key becomes auto-incrementing there, so new rows keep getting ids.
 * Foreign keys, indexes, defaults and checks are not copied.
 */
export function copyTableDdl(t: Table, from: Engine, to: Engine, schema: string): string {
  const pk = t.columns.filter((c) => c.pk);
  const autoKey = pk.length === 1 && /int|serial/i.test(pk[0].dataType) && !/unsigned/i.test(pk[0].dataType) ? pk[0].name : null;
  const lines = t.columns.map((c) => {
    let type = portType(c.dataType, from, to, c.pk);
    if (c.name === autoKey && from !== to) type = to === "postgres" ? "bigint GENERATED BY DEFAULT AS IDENTITY" : to === "mysql" ? "bigint AUTO_INCREMENT" : "INTEGER";
    return `  ${quoteIdent(to, c.name)} ${type}${c.nullable || c.pk ? "" : " NOT NULL"}`;
  });
  if (pk.length) lines.push(`  PRIMARY KEY (${pk.map((c) => quoteIdent(to, c.name)).join(", ")})`);
  return `CREATE TABLE ${qualified(to, { schema, name: t.name })} (\n${lines.join(",\n")}\n)`;
}

/** A PostgreSQL array literal ({a,"b c",NULL,{1,2}}) as a JS array; null if it isn't one. */
export function parsePgArray(s: string): unknown[] | null {
  let i = 0;
  const parse = (): unknown[] | null => {
    if (s[i] !== "{") return null;
    i++;
    const out: unknown[] = [];
    if (s[i] === "}") { i++; return out; }
    for (;;) {
      if (s[i] === "{") { const sub = parse(); if (!sub) return null; out.push(sub); }
      else if (s[i] === '"') {
        let v = ""; i++;
        while (i < s.length && s[i] !== '"') { if (s[i] === "\\") i++; v += s[i++]; }
        i++; out.push(v);
      } else {
        let v = "";
        while (i < s.length && s[i] !== "," && s[i] !== "}") v += s[i++];
        out.push(v === "NULL" ? null : v);
      }
      if (s[i] === ",") { i++; continue; }
      if (s[i] === "}") { i++; return out; }
      return null;
    }
  };
  const a = parse();
  return a && i === s.length ? a : null;
}

/**
 * A value read from `from`, made acceptable to `to`: PostgreSQL arrays become JSON, and times
 * with an offset become UTC without one for MySQL (its DATETIME rejects "+00").
 */
export function portValue(v: unknown, type: string, from: Engine, to: Engine): unknown {
  if (v === null || from === to) return v;
  // PostgreSQL won't cast 1 / 0 into a boolean column (SQLite and MySQL store booleans as numbers)
  if (to === "postgres" && portType(type, from, to) === "boolean") {
    if (v === 1 || v === "1" || v === true || v === "0x01") return true;
    if (v === 0 || v === "0" || v === false || v === "0x00") return false;
  }
  if (typeof v !== "string") return v;
  if (from === "postgres" && type.endsWith("[]")) { const a = parsePgArray(v); return a ? JSON.stringify(a) : v; }
  if (to === "mysql") {
    const m = /^(\d{4})-(\d\d)-(\d\d)[ T](\d\d):(\d\d):(\d\d)(\.\d+)?(Z|[+-]\d\d(?::?\d\d)?)$/.exec(v);
    if (m) {
      const off = m[8] === "Z" ? 0 : (m[8][0] === "-" ? -1 : 1) * (Number(m[8].slice(1, 3)) * 60 + Number(m[8].replace(":", "").slice(3, 5) || 0));
      const d = new Date(Date.UTC(+m[1], +m[2] - 1, +m[3], +m[4], +m[5], +m[6]) - off * 60000);
      const p = (n: number) => String(n).padStart(2, "0");
      return `${d.getUTCFullYear()}-${p(d.getUTCMonth() + 1)}-${p(d.getUTCDate())} ${p(d.getUTCHours())}:${p(d.getUTCMinutes())}:${p(d.getUTCSeconds())}${m[7] ?? ""}`;
    }
  }
  return v;
}

/** Byte columns: read as hex and written back as bytes, never as the grid's "0x…" display text. */
export const isBinary = (type: string) => /bytea|blob|binary/i.test(type);
const isBit = (type: string) => /^bit\b/i.test(type.trim());

/** SELECT expression for copying a column off `engine` (hex for bytes, a number for MySQL BIT). */
export function readExpr(engine: Engine, col: string, type: string): string {
  const q = quoteIdent(engine, col);
  if (isBinary(type)) return `${engine === "postgres" ? `upper(encode(${q}, 'hex'))` : engine === "mysql" ? `HEX(${q})` : `hex(${q})`} AS ${q}`;
  if (engine === "mysql" && isBit(type)) return `CAST(${q} AS UNSIGNED) AS ${q}`;
  return q;
}

/** SQL literal on `to` for a value read with readExpr from a `from` column of `type`. */
export function writeLiteral(to: Engine, v: unknown, type: string, from: Engine): string {
  if (v === null || v === undefined) return "NULL";
  if (isBinary(type) && typeof v === "string" && /^[0-9A-Fa-f]*$/.test(v)) return to === "postgres" ? `decode('${v}', 'hex')` : `X'${v}'`;
  return literal(to, portValue(v, type, from, to) as never);
}
